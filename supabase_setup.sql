-- Proyecto académico PIME: preparar una tabla nueva, sin borrar tablas existentes.
-- Modelo esperado: nomic-embed-text con 768 dimensiones, en carga y consulta.
create schema if not exists extensions;
create extension if not exists vector with schema extensions;
set search_path = public, extensions;

create table if not exists public.pime_documents (
  id bigint generated by default as identity primary key,
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  embedding vector(768) not null
);

-- Verifica una instalación previa incompatible en lugar de modificar/borrar datos.
do $$
declare embedding_type text;
begin
  select format_type(a.atttypid,a.atttypmod) into embedding_type
  from pg_attribute a
  where a.attrelid='public.pime_documents'::regclass and a.attname='embedding';
  if embedding_type <> 'vector(768)' then
    raise exception 'pime_documents.embedding debe ser vector(768); actual: %', embedding_type;
  end if;
end $$;

alter table public.pime_documents enable row level security;
revoke all on table public.pime_documents from anon, authenticated;
grant select, insert, update, delete on table public.pime_documents to service_role;
grant usage, select on sequence public.pime_documents_id_seq to service_role;

create or replace function public.match_pime_documents(
  query_embedding vector(768),
  match_count integer default 3,
  filter jsonb default '{}'::jsonb
)
returns table (id bigint, content text, metadata jsonb, similarity double precision)
language sql stable security invoker
set search_path = public, extensions
as $$
  select d.id, d.content, d.metadata,
         (1 - (d.embedding <=> query_embedding))::double precision as similarity
  from public.pime_documents d
  where d.metadata @> coalesce(filter, '{}'::jsonb)
  order by d.embedding <=> query_embedding
  limit least(greatest(coalesce(match_count,3),1),10);
$$;

revoke all on function public.match_pime_documents(vector,integer,jsonb) from public, anon, authenticated;
grant execute on function public.match_pime_documents(vector,integer,jsonb) to service_role;

-- EVIDENCIA después de cargar: cantidad, metadata y dimensiones, sin exponer claves.
select id, left(content,160) as fragmento, metadata,
       vector_dims(embedding) as dimensiones
from public.pime_documents order by id desc limit 10;
